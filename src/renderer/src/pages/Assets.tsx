import { Images, Plus } from 'lucide-react'
import { useCallback, useEffect, useMemo, useRef, useState } from 'react'
import { ASSET_KINDS, type AssetItem, type AssetKind } from '../../../shared/ipc'
import { useStudio } from '../store'
import { useWorkspaceProject } from '../lib/use-workspace-project'
import { fmtBytes } from '../lib/format'
import { Badge, Button, EmptyState, PageHeader, Select, cx } from '../components/ui'
import { errMsg } from '../components/connections/StatusBadge'
import { AssetImage } from '../components/assets/AssetImage'
import { AssetDetail } from '../components/assets/AssetDetail'
import { GenerateModal, type GenerateSeed } from '../components/assets/GenerateModal'

/** Pictures made for a project: generated by image models (by hand or by the Image Generator agent) or derived from other pictures. */
export function Assets() {
  const projects = useStudio((s) => s.projects)
  const setWorkspaceProject = useStudio((s) => s.setWorkspaceProject)
  const project = useWorkspaceProject()
  const projectId = project?.id ?? null
  const [kind, setKind] = useState<AssetKind | ''>('')
  const [items, setItems] = useState<AssetItem[]>([])
  const [loaded, setLoaded] = useState(false)
  const [error, setError] = useState<string | null>(null)
  const [selectedId, setSelectedId] = useState<string | null>(null)
  const [seed, setSeed] = useState<GenerateSeed | null>(null)
  const timer = useRef<ReturnType<typeof setTimeout> | null>(null)

  const load = useCallback(async () => {
    if (!projectId) return
    try {
      const list = await window.api.invoke('assets:list', { projectId, kind: kind || null })
      setItems(list)
      setError(null)
    } catch (e) {
      setError(errMsg(e))
    } finally {
      setLoaded(true)
    }
  }, [projectId, kind])

  useEffect(() => {
    setLoaded(false)
    void load()
  }, [load])

  // Files written by agents or by the user appear without a manual refresh.
  useEffect(() => {
    if (!projectId) return
    const off = window.api.onFsChange((c) => {
      if (c.projectId !== projectId) return
      if (timer.current) clearTimeout(timer.current)
      timer.current = setTimeout(() => void load(), 250)
    })
    return () => {
      off()
      if (timer.current) clearTimeout(timer.current)
    }
  }, [projectId, load])

  const selected = items.find((a) => a.id === selectedId) ?? null
  const parent = useMemo(() => (selected?.parentId ? (items.find((a) => a.id === selected.parentId) ?? null) : null), [items, selected])

  useEffect(() => {
    if (selectedId && loaded && !items.some((a) => a.id === selectedId)) setSelectedId(null)
  }, [items, loaded, selectedId])

  if (!project) {
    return (
      <div className="p-6">
        <PageHeader title="Asset Library" subtitle="Pictures generated for your projects." />
        <EmptyState icon={<Images size={28} />} title="No project yet">
          Create a project first: pictures are saved inside the project folder.
        </EmptyState>
      </div>
    )
  }

  const changed = async (select?: string | null) => {
    await load()
    if (select !== undefined) setSelectedId(select)
  }

  return (
    <div className="flex h-full min-h-0">
      <div className="flex min-w-0 flex-1 flex-col p-6">
        <PageHeader
          title="Asset Library"
          subtitle="Pictures made by image models for this project, and the edits derived from them."
          action={
            <Button variant="primary" onClick={() => setSeed({})} data-action="open-generate">
              <Plus size={14} /> Generate
            </Button>
          }
        />
        <div className="mb-4 flex flex-wrap items-center gap-2">
          <Select value={project.id} onChange={(e) => (setWorkspaceProject(e.target.value), setSelectedId(null))} aria-label="Project" className="w-56">
            {projects.map((p) => (
              <option key={p.id} value={p.id}>
                {p.name}
              </option>
            ))}
          </Select>
          <Select value={kind} onChange={(e) => setKind(e.target.value as AssetKind | '')} aria-label="Kind filter" className="w-40">
            <option value="">All kinds</option>
            {ASSET_KINDS.map((k) => (
              <option key={k.value} value={k.value}>
                {k.label}
              </option>
            ))}
          </Select>
          <span className="text-xs text-faint" data-asset-count={items.length}>
            {items.length} picture{items.length === 1 ? '' : 's'} · {fmtBytes(items.reduce((n, a) => n + a.bytes, 0))}
          </span>
        </div>

        {error && (
          <p role="alert" className="mb-3 rounded-md border border-err/30 bg-err/10 px-3 py-2 text-xs break-words text-err" data-selectable>
            {error}
          </p>
        )}

        {loaded && items.length === 0 ? (
          <EmptyState
            icon={<Images size={28} />}
            title={kind ? 'No pictures of this kind' : 'No pictures yet'}
            action={
              <Button variant="primary" onClick={() => setSeed({})}>
                <Plus size={14} /> Generate the first one
              </Button>
            }
          >
            Generate pictures here, or give the Image Generator agent tasks on the board. Files are saved under the project’s assets folder.
          </EmptyState>
        ) : (
          <ul className="grid min-h-0 flex-1 content-start gap-3 overflow-y-auto pr-1" style={{ gridTemplateColumns: 'repeat(auto-fill, minmax(150px, 1fr))' }}>
            {items.map((a) => (
              <li key={a.id}>
                <button
                  data-asset={a.name}
                  data-kind={a.kind}
                  aria-current={a.id === selectedId}
                  onClick={() => setSelectedId(a.id)}
                  className={cx(
                    'group w-full overflow-hidden rounded-lg border bg-panel text-left transition-colors',
                    a.id === selectedId ? 'border-accent ring-1 ring-accent' : 'border-line hover:border-faint'
                  )}
                >
                  <AssetImage asset={a} max={256} className="aspect-square w-full" />
                  <div className="space-y-0.5 px-2 py-1.5">
                    <p className="truncate text-xs font-medium" title={a.path}>
                      {a.name}
                    </p>
                    <p className="flex items-center gap-1 text-[11px] text-faint">
                      {a.width ? `${a.width}×${a.height}` : '—'}
                      {a.origin === 'processed' && <Badge>edit</Badge>}
                    </p>
                  </div>
                </button>
              </li>
            ))}
          </ul>
        )}
      </div>

      <aside className="w-[380px] shrink-0 border-l border-line bg-panel" aria-label="Picture details">
        {selected ? (
          <AssetDetail
            key={selected.id}
            asset={selected}
            parent={parent}
            onChanged={(id) => void changed(id)}
            onSelect={setSelectedId}
            onVariation={(a) => setSeed({ reference: a, prompt: '', kind: a.kind, connectionId: a.connectionId, model: a.model, transparent: a.transparent, name: `${a.name}-variation` })}
            onRegenerate={(a) => setSeed({ prompt: a.prompt ?? '', kind: a.kind, connectionId: a.connectionId, model: a.model, transparent: a.transparent, name: a.name })}
          />
        ) : (
          <p className="p-6 text-xs text-faint">Select a picture to see its prompt, model and size, and to edit it.</p>
        )}
      </aside>

      {seed && (
        <GenerateModal
          project={project}
          seed={seed}
          onClose={() => setSeed(null)}
          onDone={(r) => {
            void changed(r.assets[0]?.id ?? undefined)
          }}
        />
      )}
    </div>
  )
}
